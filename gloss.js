// GL = glossPage(esc): h(text) بيرجّع HTML مع أرقام فوق الكلمات الإنجليزية، وlist(reveal) بيرسم الشرح تحت الصفحة.
window.glossPage = function (esc) {
  const G = window.GLOSS || {};
  const keys = Object.keys(G).sort((a, b) => b.length - a.length);
  const rx = keys.map((k) => k.replace(/[.*+?^${}()|[\]\\\/]/g, '\\$&')).join('|');
  const order = [];
  function h(text) {
    text = String(text == null ? '' : text);
    if (!rx) return esc(text);
    const re = new RegExp('(' + rx + ')', 'g');
    let out = '', last = 0, m;
    while ((m = re.exec(text))) {
      const t = m[1], i = m.index, before = text.slice(0, i), after = text.charAt(i + t.length);
      const pc = before.slice(-1);
      const okBefore = G[t].u ? /\d\s?$/.test(before) : !/[A-Za-z]/.test(pc);
      const okAfter = !/[A-Za-z0-9²]/.test(after);
      if (!okBefore || !okAfter) { re.lastIndex = i + 1; continue; }
      let n = order.indexOf(t); if (n < 0) { order.push(t); n = order.length - 1; }
      const num = (before.slice(last).match(/[\d.,×x+\-]*\d\s?$/) || [''])[0];   // الرقم مع الوحدة: 220V بيضلّوا سوا
      out += esc(text.slice(last, i - num.length)) + `<bdi dir="ltr" class="en">${esc(num + t)}<sup class="gn">${n + 1}</sup></bdi>`;
      last = i + t.length;
    }
    return out + esc(text.slice(last));
  }
  function list(reveal) {
    if (!order.length) return '';
    return `<div class="gloss"><div class="gh">الكلمات الإنجليزية بهالصفحة${reveal ? '' : ' <span>(شو يعني كل وحدة بيبيّن بعد ما تجاوب صح)</span>'}</div><ol>${order.map((t, i) => {
      const g = G[t];
      return `<li><sup>${i + 1}</sup> <bdi dir="ltr" class="en">${esc(t)}</bdi> <span class="rd">بتنقرا «${esc(g.r)}»</span>${reveal ? `<span class="mn">: ${esc(g.m)}</span>` : ''}</li>`;
    }).join('')}</ol></div>`;
  }
  return { h, list };
};
